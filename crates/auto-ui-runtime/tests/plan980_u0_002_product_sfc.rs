//! PLAN-980 U0 产品出口验收（④-A #5，用户 2026-11-18 指令）：002 的
//! 可运行产物从**产品生成入口**（`generate_sfc_with_lane_product`）取得，
//! 页面从正常生成结果启动——**去掉 U0 预验收夹具的两步注入**（a2x_rt
//! import 由测试制造 + rt 文件由测试供页）：import 由生成器显式发射、
//! rt 模块为产品返回物原样落盘。TS 处理=标准 Vue 工具链转换
//! （`@vue/compiler-sfc` + esbuild——vite 同族引擎），非夹具私改。
//! 断言复用 U0 判据：计数（0→1→0，加/减/重置真实点击）、无旧 TS 回退
//! （absent 空 + 拼接体 a2x 形）。
use auto_ui_runtime::ui::ace_vue_script::{generate_sfc_with_lane_product, LaneSfcProduct};

fn src_002() -> String {
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let at = manifest.join("../../examples/ui/002-counter/src/front/app.at");
    std::fs::read_to_string(&at).unwrap_or_else(|e| panic!("002 source: {e}"))
}

fn product_002() -> LaneSfcProduct {
    generate_sfc_with_lane_product(&src_002(), "p980-u0-product-002.at")
        .expect("unmodified 002 generates a product lane SFC")
}

/// ①产品档（CPU）：生成器显式发射 a2x_rt import（名字=脚本引用 ∩ 官方
/// rt 导出面）、rt 模块随产物返回、lane 证据保持（absent 空 + a2x 形，
/// 旧 TS fallback 不在位）。
#[test]
fn p980_u0_product_sfc_carries_explicit_rt_import_and_lane_bodies() {
    let product = product_002();
    let LaneSfcProduct {
        sfc,
        runtime_mjs,
        lane_bodies,
        absent,
    } = &product;
    assert!(absent.is_empty(), "product keeps all-lane: {absent:?}");
    assert_eq!(lane_bodies.len(), 9, "6 on-block + 3 view lambdas");

    // 显式 import：002 脚本引用的官方 rt 名=Inc/Dec 的 add/sub 与
    // UseAuto/UseSolarized 的 str 三件（集合比对——函数序不属合同）。
    let import_at = sfc
        .find("from \"./a2x_rt.mjs\"")
        .expect("generator emits the explicit a2x_rt import");
    let line_start = sfc[..import_at].rfind("import").expect("import kw");
    let import_line = &sfc[line_start..import_at];
    let mut names: Vec<&str> = import_line
        .trim()
        .trim_start_matches("import {")
        .trim_end()
        .trim_end_matches("}")
        .split(',')
        .map(|n| n.trim())
        .filter(|n| !n.is_empty())
        .collect();
    names.sort_unstable();
    assert_eq!(
        names,
        vec![
            "a2x_add",
            "a2x_str_free",
            "a2x_str_lit",
            "a2x_str_to_owned",
            "a2x_sub"
        ],
        "import carries exactly the referenced official rt names: {import_line}"
    );
    // rt 模块=官方 script_runtime_body 原样（导出面含全部被引名）。
    for name in [
        "a2x_add",
        "a2x_sub",
        "a2x_str_lit",
        "a2x_str_to_owned",
        "a2x_str_free",
    ] {
        assert!(
            runtime_mjs.contains(&format!("export function {name}(")),
            "official rt exports {name}"
        );
    }
    assert!(
        runtime_mjs.starts_with("// AUTO-GENERATED by auto-a2x-ts (PLAN-976)"),
        "rt is the official script_runtime_body artifact"
    );
    // lane 证据保持：拼接体 a2x 形、旧 TS fallback 不在位（生成级判据复用）。
    assert!(
        sfc.contains("a2x_add(count.value, 1)"),
        "Inc lane body (加)"
    );
    assert!(
        sfc.contains("a2x_sub(count.value, 1)"),
        "Dec lane body (减)"
    );
    assert!(sfc.contains("count.value = 0;"), "Reset lane body (重置)");
    assert!(
        !sfc.contains("count.value += 1") && !sfc.contains("count.value -= 1"),
        "no old TS fallback form for the count handlers"
    );
}

/// ②挂载档（排窗 `AUTO_UI_ACE_WEB_E2E=1`）：页面从**产品产物树**启动——
/// SFC 与 `a2x_rt.mjs` 均为产品返回物原样落盘，rig 零注入（不扫名、不写
/// import、不供 rt 内容）；唯一改写=裸 `'vue'` 说明符的 dev-server 式别名
/// （vite 同职责，模块解析非产物内容）。断言=U0 判据全量复用。
#[test]
fn p980_u0_product_sfc_mounts_and_counts() {
    if std::env::var("AUTO_UI_ACE_WEB_E2E").ok().as_deref() != Some("1") {
        eprintln!(
            "p980_u0_product_sfc_mounts_and_counts: not scheduled \
             (set AUTO_UI_ACE_WEB_E2E=1; browser tier, playwright + vue required)"
        );
        return;
    }
    let product = product_002();
    assert!(
        product.absent.is_empty() && product.lane_bodies.len() == 9,
        "mount tier requires the all-lane product SFC (absent={:?})",
        product.absent
    );
    let dir = std::env::temp_dir().join(format!("p980-u0-product-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    // 产品产物原样落盘（import 引用 `./a2x_rt.mjs`——同目录解析）。
    std::fs::write(dir.join("component.sfc"), &product.sfc).unwrap();
    std::fs::write(dir.join("a2x_rt.mjs"), &product.runtime_mjs).unwrap();
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let script = manifest.join("../../examples/ui/ace-web-lane/tests/test_002_product_mount.mjs");
    let node = std::env::var("A2TS_NODE").unwrap_or_else(|_| "node".into());
    let out = std::process::Command::new(&node)
        .arg(script.to_str().unwrap())
        .arg(dir.to_str().unwrap())
        .output()
        .expect("node spawn");
    let stdout = String::from_utf8_lossy(&out.stdout).to_string();
    let stderr = String::from_utf8_lossy(&out.stderr).to_string();
    let _ = std::fs::remove_dir_all(&dir);
    assert!(
        out.status.success() && stdout.contains("U0_002_PRODUCT_MOUNT_OK"),
        "002 product mount: {stdout} / {stderr}"
    );
    for line in stdout
        .lines()
        .filter(|l| l.starts_with("[+]") || l.starts_with("[-]"))
    {
        eprintln!("{line}");
    }
}
