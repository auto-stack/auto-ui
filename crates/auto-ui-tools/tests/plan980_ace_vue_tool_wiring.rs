#[test]
fn p980_ace_vue_tool_wiring_key_gate_and_named_rejects() {
    // ── ①键未设：负控源走 legacy 道（Ok，无 lane 判据）——零行为变化。
    let ws0 = temp_workspace("key-off");
    std::env::remove_var("AUTO_UI_ACE_VUE");
    let n = incremental_compile_changed(&ws0, None).expect("legacy track ok");
    assert!(n > 0, "002 has incremental outputs");
    let app0 = std::fs::read_to_string(ws0.join("gen/front/vue/src/App.vue")).unwrap();
    assert!(
        !app0.contains("./a2x_rt.mjs"),
        "legacy track carries no a2x_rt import"
    );
    assert!(
        !ws0.join("gen/front/vue/src/a2x_rt.mjs").exists(),
        "legacy track writes no rt module"
    );
    assert!(!ws0.join("gen/front/vue/src/a2x_rt.d.mts").exists());
    let legacy = VueProject::from_workspace(&ws0).expect("legacy root project");
    assert!(legacy.shadcn_components.iter().any(|name| name == "button"));
    let _ = std::fs::remove_dir_all(&ws0);

    // ── ②键在场：002 增量道 App.vue=产品 lane 产物 + 官方 rt 落盘。
    std::env::set_var("AUTO_UI_ACE_VUE", "1");
    let ws1 = temp_workspace("key-on-incr");
    incremental_compile_changed(&ws1, None).expect("ace lane incremental ok");
    let app1 = std::fs::read_to_string(ws1.join("gen/front/vue/src/App.vue")).unwrap();
    assert!(
        app1.contains("a2x_add(count.value, 1)"),
        "App.vue carries the lane Inc body"
    );
    assert!(
        app1.contains("from \"./a2x_rt.mjs\""),
        "App.vue carries the explicit rt import: {}…",
        &app1[..app1.len().min(300)]
    );
    let rt = std::fs::read_to_string(ws1.join("gen/front/vue/src/a2x_rt.mjs"))
        .expect("official rt written next to App.vue");
    assert!(rt.starts_with("// AUTO-GENERATED by auto-a2x-ts (PLAN-976)"));
    assert!(rt.contains("export function a2x_add("));
    let decl_path = ws1.join("gen/front/vue/src/a2x_rt.d.mts");
    let declaration = std::fs::read_to_string(&decl_path).expect("incremental runtime declaration");
    assert_eq!(
        declaration,
        auto_ui_runtime::ui::ace_vue_script::script_runtime_declaration()
    );

    // ── ③键在场：全量道（from_workspace）app_vue_code=产品 lane 产物，
    ///    rt 随 Self 携带并按写盘点落盘。
    let project = VueProject::from_workspace(&ws1).expect("from_workspace with lane ok");
    assert!(
        project.app_vue_code.contains("a2x_add(count.value, 1)"),
        "full-path root widget SFC is the lane product"
    );
    assert!(project.app_vue_code.contains("<button"));
    assert!(
        project.shadcn_components.iter().all(|name| name != "button"),
        "the ACE root uses an HTML button and carries no shadcn button scaffold"
    );
    assert!(project.ace_vue_rt.is_some(), "rt rides the project");
    std::fs::remove_file(&decl_path).expect("remove incremental declaration before full write");
    project.write_ace_vue_rt().expect("rt write ok");
    let rt2 = std::fs::read_to_string(ws1.join("gen/front/vue/src/a2x_rt.mjs")).unwrap();
    assert_eq!(rt2, rt, "rt write is idempotent content");
    assert_eq!(std::fs::read_to_string(decl_path).unwrap(), declaration);
    let _ = std::fs::remove_dir_all(&ws1);

    // ── ④键在场：lane 缺席源=具名拒绝（不静默落 legacy）。
    let ws2 = temp_workspace("absent");
    std::fs::write(ws2.join("src/front/app.at"), ABSENT_SRC).unwrap();
    let err = incremental_compile_changed(&ws2, None)
        .expect_err("lane-absent source must be named-rejected under the key");
    let msg = err.to_string();
    assert!(
        msg.contains("ace.vue-lane-unsupported") && msg.contains(".Set"),
        "named rejection names the code and the absent handler: {msg}"
    );
    // from_workspace 同律。
    let err2 = match VueProject::from_workspace(&ws2) {
        Err(e) => e,
        Ok(_) => panic!("full path must reject lane-absent source under the key"),
    };
    assert!(
        err2.to_string().contains("ace.vue-lane-unsupported"),
        "full-path named rejection: {}",
        err2.to_string()
    );
    let _ = std::fs::remove_dir_all(&ws2);

    // ── ⑥键在场·多 widget 增量道：根=App.vue（自己的 lane 体）、其余=
    //    src/components/{W}.vue（各自的 lane 体+`../a2x_rt.mjs` href）。
    let ws4 = temp_workspace("multi-incr");
    std::fs::write(ws4.join("src/front/app.at"), MULTI_SRC).unwrap();
    incremental_compile_changed(&ws4, None).expect("multi-widget incremental ok");
    let app_multi = std::fs::read_to_string(ws4.join("gen/front/vue/src/App.vue")).unwrap();
    assert!(
        app_multi.contains("a2x_add(count.value, 1)") && app_multi.contains("./a2x_rt.mjs"),
        "root artifact carries its own lane body + root-relative rt href"
    );
    assert!(
        !app_multi.contains("(!flag.value)"),
        "root artifact must NOT carry the second widget's handler"
    );
    let panel = std::fs::read_to_string(ws4.join("gen/front/vue/src/components/Panel.vue"))
        .expect("second widget lands in its own component artifact");
    assert!(
        panel.contains("(!flag.value)") && panel.contains("a2x_add(steps.value, 1)"),
        "component artifact carries its own lane bodies (NOT form + helper form)"
    );
    assert!(
        panel.contains("../a2x_rt.mjs"),
        "component artifact carries the component-relative rt href"
    );
    assert!(
        !panel.contains("a2x_add(count.value, 1)"),
        "component artifact must NOT carry the root's handler"
    );

    // ── ⑦键在场·多 widget 全量道：from_workspace 逐件对位（root + panel
    //    组件项均为产品 lane 件）。
    let project2 = VueProject::from_workspace(&ws4).expect("multi full path ok");
    let root_entry = project2
        .components
        .iter()
        .find(|(_, name, _, _)| name == "app")
        .expect("root entry");
    assert!(root_entry.2.contains("a2x_add(count.value, 1)"));
    let panel_entry = project2
        .components
        .iter()
        .find(|(_, _, _, w)| w == "Panel")
        .expect("panel entry");
    assert!(
        panel_entry.2.contains("(!flag.value)")
            && panel_entry.2.contains("a2x_add(steps.value, 1)"),
        "full-path panel entry is the lane product"
    );
    assert!(
        panel_entry.2.contains("../a2x_rt.mjs"),
        "full-path panel entry carries the component-relative rt href"
    );
    assert!(project2.ace_vue_rt.is_some());
    project2.write_ace_vue_rt().expect("rt write ok");
    let _ = std::fs::remove_dir_all(&ws4);

    // ── ⑧键在场·多 widget 缺席：具名拒携带 widget 名（Panel[.Set]）。
    let ws5 = temp_workspace("multi-absent");
    std::fs::write(ws5.join("src/front/app.at"), MULTI_ABSENT_SRC).unwrap();
    let err3 = incremental_compile_changed(&ws5, None)
        .expect_err("multi-widget absent must be named-rejected with the widget name");
    assert!(
        err3.to_string().contains("ace.vue-lane-unsupported")
            && err3.to_string().contains("Panel")
            && err3.to_string().contains(".Set"),
        "named rejection names widget+handler: {}",
        err3.to_string()
    );
    let _ = std::fs::remove_dir_all(&ws5);

    // ── ⑨键在场·components/ 通道（④-A #9）：原样 AutoNotes `fp_editor.at`
    //    的 lane-ready 派生件（去 if-else view 形——981 域 view 面缺口具名）
    //    编入正确的 Vue 组件（src/components/{W}.vue=产品件+组件位 href）。
    let ws6 = temp_workspace("components-incr");
    let comp_dir = ws6.join("src/front/components");
    std::fs::create_dir_all(&comp_dir).unwrap();
    std::fs::write(
        comp_dir.join("fp_lite.at"),
        "widget FpNoteEditorLite (mode: str) {
    msg { DraftEdit(str) }

    model {
        var last_text str = \"\"
    }

    view {
        col {
            textarea { value: .last_text, oninput: .DraftEdit, placeholder: \"FP body\" }
        }
    }

    on {
        .DraftEdit(v) -> { .last_text = v }
    }
}
",
    )
    .unwrap();
    incremental_compile_changed(&ws6, None).expect("components channel incremental ok");
    let fp_artifact =
        std::fs::read_to_string(ws6.join("gen/front/vue/src/components/FpNoteEditorLite.vue"))
            .expect("components channel writes the widget artifact");
    // PLAN-1072 刀C 具名修订（str 边界统一）：形参读=a2x_str_lit 包裹、
    // 写=解码+释放 owned 副本（宿主裸串 ↔ rt 文本边界）。
    assert!(
        fp_artifact.contains("a2x_str_clone(a2x_str_lit(v))")
            && fp_artifact.contains("last_text.value = a2x_str_utf8(t0);"),
        "component artifact carries the DraftEdit lane body (marshalled)"
    );
    assert!(
        fp_artifact.contains("../a2x_rt.mjs"),
        "component artifact carries the component-relative rt href"
    );
    assert!(
        ws6.join("gen/front/vue/src/a2x_rt.mjs").exists(),
        "official rt lands in src/ (shared with the app channel)"
    );

    // ── ⑨b 全量道同律：from_workspace 的 components 条目=产品件。
    let project3 = VueProject::from_workspace(&ws6).expect("components full path ok");
    let fp_entry = project3
        .components
        .iter()
        .find(|(_, _, _, w)| w == "FpNoteEditorLite")
        .expect("components entry");
    // PLAN-1072 刀C 具名修订：同 ⑨a 的 marshal 包裹形。
    assert!(
        fp_entry.2.contains("a2x_str_clone(a2x_str_lit(v))")
            && fp_entry.2.contains("../a2x_rt.mjs"),
        "full-path components entry is the lane product"
    );

    // ── ⑨c键在场·**原样 AutoNotes fp_editor.at**（view-if 刀后 lane 就绪）
    //    经 components/ 通道编入正确组件（DraftEdit lane 体+组件位 href）。
    {
        let ws6b = temp_workspace("components-fp-orig");
        let comp_dir6b = ws6b.join("src/front/components");
        std::fs::create_dir_all(&comp_dir6b).unwrap();
        let fp_src =
            std::fs::read_to_string("D:/autostack/auto-notes/src/front/components/fp_editor.at")
                .expect("auto-notes fp_editor.at readable");
        std::fs::write(comp_dir6b.join("fp_editor.at"), fp_src).unwrap();
        incremental_compile_changed(&ws6b, None)
            .expect("original fp_editor generates through the components channel");
        let fp_orig =
            std::fs::read_to_string(ws6b.join("gen/front/vue/src/components/FpNoteEditor.vue"))
                .expect("original FpNoteEditor artifact written");
        // PLAN-1072 刀C 具名修订：同 ⑨a（marshal 包裹形）。
        assert!(
            fp_orig.contains("a2x_str_clone(a2x_str_lit(v))") && fp_orig.contains("../a2x_rt.mjs"),
            "original fp_editor artifact carries the DraftEdit lane body + component href"
        );
        let _ = std::fs::remove_dir_all(&ws6b);
    }

    // ── ⑩键在场·components/ 缺席负控：具名拒附文件名+widget 名。
    let ws7 = temp_workspace("components-absent");
    let comp_dir2 = ws7.join("src/front/components");
    std::fs::create_dir_all(&comp_dir2).unwrap();
    std::fs::write(
        comp_dir2.join("bad_comp.at"),
        "widget BadComp {
    msg Msg { Set(int) }

    model {
        var n int = 0
    }

    view {
        col { text \"B\" }
    }

    on {
        .Set(n) -> { .n = n }
    }
}
",
    )
    .unwrap();
    let err4 = incremental_compile_changed(&ws7, None)
        .expect_err("components-file absent must be named-rejected with the file name");
    let msg4 = err4.to_string();
    assert!(
        msg4.contains("ace.vue-lane-unsupported")
            && msg4.contains("bad_comp.at")
            && msg4.contains("BadComp"),
        "named rejection names the components file and widget: {msg4}"
    );
    let _ = std::fs::remove_dir_all(&ws7);
    let _ = std::fs::remove_dir_all(&ws6);

    let routed = temp_workspace("routed-checked-components");
    let front = routed.join("src/front");
    std::fs::create_dir_all(front.join("pages")).unwrap();
    std::fs::create_dir_all(front.join("components")).unwrap();
    std::fs::write(front.join("app.at"), r#"widget App {
    routes { "/" -> use chart }
    view { outlet }
}
"#).unwrap();
    std::fs::write(front.join("pages/chart.at"), r#"widget Chart {
    use { package: official from "../components" }
    view { chart-legend {} }
}
"#).unwrap();
    std::fs::write(front.join("components/package.at"), "name: \"official\"\nversion: \"0.1.0\"\n").unwrap();
    std::fs::write(front.join("components/chart_legend.at"), r#"widget ChartLegend {
    msg { Build }
    model { steps List = [] }
    on {
        .Build -> {
            var points List = []
            points.push(1.0)
            .steps = points
        }
    }
    view {
        button "Build chart" { onclick: .Build }
        text f"${.steps.len()}" {}
    }
}
"#).unwrap();
    let project = VueProject::from_workspace(&routed).expect("full checked route generation");
    assert!(project.components.iter().any(|(dir, name, sfc, _)| {
        dir == "pages" && name == "chart" && sfc.contains("<AcePackageView />")
    }));
    assert!(!project.components.iter().any(|(_, _, _, name)| name == "ChartLegend"));
    incremental_compile_changed(&routed, None).expect("incremental checked route generation");
    let routed_vue = routed.join("gen/front/vue/src");
    let chart_page = std::fs::read_to_string(routed_vue.join("pages/chart.vue")).unwrap();
    assert!(chart_page.contains("<AcePackageView />"));
    assert!(!routed_vue.join("components/ChartLegend.vue").exists());
    let _ = std::fs::remove_dir_all(&routed);

    // ── ⑤键未设：同一缺席源恢复 legacy Ok（拒绝只在键下收紧）。
    std::env::remove_var("AUTO_UI_ACE_VUE");
    let ws3 = temp_workspace("absent-key-off");
    std::fs::write(ws3.join("src/front/app.at"), ABSENT_SRC).unwrap();
    incremental_compile_changed(&ws3, None).expect("key off: legacy track accepts it");
    let _ = std::fs::remove_dir_all(&ws3);
}
