//! PLAN-980 ④-A #7（982 round-184 合同）：**工具侧读键接线验收**——
//! `AUTO_UI_ACE_VUE=1` 时 `auto run`（Vue）生成道的 app.at SFC 走产品
//! lane 入口（`generate_sfc_with_lane_product`：lane 体 + 显式
//! `./a2x_rt.mjs` import + 官方 rt 落盘）；lane 缺席=**具名拒绝**（不静默
//! 落 legacy）；键未设=legacy 生成道逐字不变。
//! 单测试函数顺序执行（env 键进程级——线程间不可并行切换）。
use auto_ui_tools::vue::{incremental_compile_changed, VueProject};

fn copy_dir(src: &std::path::Path, dst: &std::path::Path) {
    std::fs::create_dir_all(dst).unwrap();
    for entry in std::fs::read_dir(src).unwrap().flatten() {
        let p = entry.path();
        let to = dst.join(entry.file_name());
        if p.is_dir() {
            copy_dir(&p, &to);
        } else {
            std::fs::copy(&p, &to).unwrap();
        }
    }
}

fn temp_workspace(tag: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("p980-acevue-{}-{}", tag, std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let ex002 = manifest.join("../../examples/ui/002-counter");
    copy_dir(&ex002, &dir);
    dir
}

/// 多 widget 真实形源（002 族计数器 + 独立 Panel 开关——两件 handler 均
/// lane 可派生；④-A #8 逐件产物判据）。
const MULTI_SRC: &str = "widget App {
    msg { Inc }

    model {
        var count int = 0
    }

    view {
        col {
            text `C: ${.count}`
            button \"+\" { onclick: .Inc }
        }
    }

    on {
        .Inc -> { .count += 1 }
    }
}

widget Panel {
    msg { Toggle, Bump }

    model {
        var flag bool = false
        var steps int = 0
    }

    view {
        col {
            button \"T\" { onclick: .Toggle }
            button \"B\" { onclick: .Bump }
        }
    }

    on {
        .Toggle -> { .flag = !.flag }
        .Bump -> { .steps += 1 }
    }
}
";

/// 多 widget 缺席负控：Panel 的 handler 为 F-1 形参遮蔽族（具名缺席）。
const MULTI_ABSENT_SRC: &str = "widget App {
    msg { Inc }

    model {
        var count int = 0
    }

    view {
        col { text \"C\" }
    }

    on {
        .Inc -> { .count += 1 }
    }
}

widget Panel {
    msg Msg { Set(int) }

    model {
        var n int = 0
    }

    view {
        col { text \"P\" }
    }

    on {
        .Set(n) -> { .n = n }
    }
}
";

/// lane 缺席负控源（F-1 形参遮蔽族——具名缺席，永久反例先例）。
const ABSENT_SRC: &str = "widget S {\n    msg Msg { Set(int) }\n\n    model {\n        var n int = 0\n    }\n\n    view {\n        col { text \"S\" }\n    }\n\n    on {\n        .Set(n) -> { .n = n }\n    }\n}\n";

#[test]
fn p980_ace_vue_tool_wiring_key_gate_and_named_rejects() {
    // ── ①键未设：负控源走 legacy 道（Ok，无 lane 判据）——零行为变化。
    let ws0 = temp_workspace("key-off");
    std::env::remove_var("AUTO_UI_ACE_VUE");
    let n = incremental_compile_changed(&ws0, None).expect("legacy track ok");
    assert!(n > 0, "002 has incremental outputs");
    let app0 = std::fs::read_to_string(ws0.join("gen/front/vue/src/App.vue")).unwrap();
    assert!(
        !app0.contains("./a2x_rt.mjs"),
        "legacy track carries no a2x_rt import"
    );
    assert!(
        !ws0.join("gen/front/vue/src/a2x_rt.mjs").exists(),
        "legacy track writes no rt module"
    );
    let _ = std::fs::remove_dir_all(&ws0);

    // ── ②键在场：002 增量道 App.vue=产品 lane 产物 + 官方 rt 落盘。
    std::env::set_var("AUTO_UI_ACE_VUE", "1");
    let ws1 = temp_workspace("key-on-incr");
    incremental_compile_changed(&ws1, None).expect("ace lane incremental ok");
    let app1 = std::fs::read_to_string(ws1.join("gen/front/vue/src/App.vue")).unwrap();
    assert!(
        app1.contains("a2x_add(count.value, 1)"),
        "App.vue carries the lane Inc body"
    );
    assert!(
        app1.contains("from \"./a2x_rt.mjs\""),
        "App.vue carries the explicit rt import: {}…",
        &app1[..app1.len().min(300)]
    );
    let rt = std::fs::read_to_string(ws1.join("gen/front/vue/src/a2x_rt.mjs"))
        .expect("official rt written next to App.vue");
    assert!(rt.starts_with("// AUTO-GENERATED by auto-a2x-ts (PLAN-976)"));
    assert!(rt.contains("export function a2x_add("));

    // ── ③键在场：全量道（from_workspace）app_vue_code=产品 lane 产物，
    ///    rt 随 Self 携带并按写盘点落盘。
    let project = VueProject::from_workspace(&ws1).expect("from_workspace with lane ok");
    assert!(
        project.app_vue_code.contains("a2x_add(count.value, 1)"),
        "full-path root widget SFC is the lane product"
    );
    assert!(project.ace_vue_rt.is_some(), "rt rides the project");
    project.write_ace_vue_rt().expect("rt write ok");
    let rt2 = std::fs::read_to_string(ws1.join("gen/front/vue/src/a2x_rt.mjs")).unwrap();
    assert_eq!(rt2, rt, "rt write is idempotent content");
    let _ = std::fs::remove_dir_all(&ws1);

    // ── ④键在场：lane 缺席源=具名拒绝（不静默落 legacy）。
    let ws2 = temp_workspace("absent");
    std::fs::write(ws2.join("src/front/app.at"), ABSENT_SRC).unwrap();
    let err = incremental_compile_changed(&ws2, None)
        .expect_err("lane-absent source must be named-rejected under the key");
    let msg = err.to_string();
    assert!(
        msg.contains("ace.vue-lane-unsupported") && msg.contains(".Set"),
        "named rejection names the code and the absent handler: {msg}"
    );
    // from_workspace 同律。
    let err2 = match VueProject::from_workspace(&ws2) {
        Err(e) => e,
        Ok(_) => panic!("full path must reject lane-absent source under the key"),
    };
    assert!(
        err2.to_string().contains("ace.vue-lane-unsupported"),
        "full-path named rejection: {}",
        err2.to_string()
    );
    let _ = std::fs::remove_dir_all(&ws2);

    // ── ⑥键在场·多 widget 增量道：根=App.vue（自己的 lane 体）、其余=
    //    src/components/{W}.vue（各自的 lane 体+`../a2x_rt.mjs` href）。
    let ws4 = temp_workspace("multi-incr");
    std::fs::write(ws4.join("src/front/app.at"), MULTI_SRC).unwrap();
    incremental_compile_changed(&ws4, None).expect("multi-widget incremental ok");
    let app_multi = std::fs::read_to_string(ws4.join("gen/front/vue/src/App.vue")).unwrap();
    assert!(
        app_multi.contains("a2x_add(count.value, 1)") && app_multi.contains("./a2x_rt.mjs"),
        "root artifact carries its own lane body + root-relative rt href"
    );
    assert!(
        !app_multi.contains("(!flag.value)"),
        "root artifact must NOT carry the second widget's handler"
    );
    let panel = std::fs::read_to_string(ws4.join("gen/front/vue/src/components/Panel.vue"))
        .expect("second widget lands in its own component artifact");
    assert!(
        panel.contains("(!flag.value)") && panel.contains("a2x_add(steps.value, 1)"),
        "component artifact carries its own lane bodies (NOT form + helper form)"
    );
    assert!(
        panel.contains("../a2x_rt.mjs"),
        "component artifact carries the component-relative rt href"
    );
    assert!(
        !panel.contains("a2x_add(count.value, 1)"),
        "component artifact must NOT carry the root's handler"
    );

    // ── ⑦键在场·多 widget 全量道：from_workspace 逐件对位（root + panel
    //    组件项均为产品 lane 件）。
    let project2 = VueProject::from_workspace(&ws4).expect("multi full path ok");
    let root_entry = project2
        .components
        .iter()
        .find(|(_, name, _, _)| name == "app")
        .expect("root entry");
    assert!(root_entry.2.contains("a2x_add(count.value, 1)"));
    let panel_entry = project2
        .components
        .iter()
        .find(|(_, _, _, w)| w == "Panel")
        .expect("panel entry");
    assert!(
        panel_entry.2.contains("(!flag.value)")
            && panel_entry.2.contains("a2x_add(steps.value, 1)"),
        "full-path panel entry is the lane product"
    );
    assert!(
        panel_entry.2.contains("../a2x_rt.mjs"),
        "full-path panel entry carries the component-relative rt href"
    );
    assert!(project2.ace_vue_rt.is_some());
    project2.write_ace_vue_rt().expect("rt write ok");
    let _ = std::fs::remove_dir_all(&ws4);

    // ── ⑧键在场·多 widget 缺席：具名拒携带 widget 名（Panel[.Set]）。
    let ws5 = temp_workspace("multi-absent");
    std::fs::write(ws5.join("src/front/app.at"), MULTI_ABSENT_SRC).unwrap();
    let err3 = incremental_compile_changed(&ws5, None)
        .expect_err("multi-widget absent must be named-rejected with the widget name");
    assert!(
        err3.to_string().contains("ace.vue-lane-unsupported")
            && err3.to_string().contains("Panel")
            && err3.to_string().contains(".Set"),
        "named rejection names widget+handler: {}",
        err3.to_string()
    );
    let _ = std::fs::remove_dir_all(&ws5);

    // ── ⑤键未设：同一缺席源恢复 legacy Ok（拒绝只在键下收紧）。
    std::env::remove_var("AUTO_UI_ACE_VUE");
    let ws3 = temp_workspace("absent-key-off");
    std::fs::write(ws3.join("src/front/app.at"), ABSENT_SRC).unwrap();
    incremental_compile_changed(&ws3, None).expect("key off: legacy track accepts it");
    let _ = std::fs::remove_dir_all(&ws3);
}
