    results["bg11-main/template_rows"] = "8 rows; shard scales 0.5/0.6/0.7; park invisible"
    # 引用参数 SoA 列：三同定义 Coin 逐实例具名绑定（槽 0,1,2 / 模板行
    # 3,4,5 / pair 0,1,2）；Player/Hazard/Goal/VoidTrap 各自列；八状态
