    scene = jload(os.path.join(PRODUCTS_DIR, "bg11-main", "scene.agscene"))
    objs = scene["objects"]
    assert len(objs) == 8, f"bg11-main scene rows {len(objs)}"
    want = [
        ("ground", "cylinder"),
        ("Main/hero/body", "cylinder"),
        ("ShardA", "mob"),
        ("ShardB", "mob"),
        ("ShardC", "mob"),
        ("Saw", "cylinder"),
        ("Beacon", "cylinder"),
        ("VoidZone", "cylinder"),
    ]
    got = [(o["name"], o["kind"]) for o in objs]
    assert got == want, f"bg11-main rows {got}"
    scales = [o["scale"] for o in objs[2:5]]
    assert scales == [[0.5, 0.5, 0.5], [0.6, 0.6, 0.6], [0.7, 0.7, 0.7]], scales
