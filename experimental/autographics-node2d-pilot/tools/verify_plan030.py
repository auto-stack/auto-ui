def control_cold_regen(results, workdir):
    for prod in PRODUCTS:
        pdir = os.path.join(PRODUCTS_DIR, prod)
        identity = jload(os.path.join(pdir, "identity.json"))
        b = os.path.join(workdir, f"{prod}-B")
        os.makedirs(b, exist_ok=True)
        for name in os.listdir(os.path.join(pdir, "closure")):
            shutil.copyfile(os.path.join(pdir, "closure", name), os.path.join(b, name))
        r = lower(os.path.join(b, "main.at"), os.path.join(workdir, f"{prod}-B-out"))
        assert r.returncode == 0, f"{prod}: cold regen failed: {r.stderr}"
        for artifact in ("scene.agscene",):
            a = open(os.path.join(pdir, artifact), "rb").read()
            c = open(os.path.join(workdir, f"{prod}-B-out", artifact), "rb").read()
            assert a == c, f"{prod}: cold A->B {artifact} not byte-equal"
        if identity["user_source_sha256"] is not None:
            a = open(os.path.join(pdir, "world.at"), "rb").read()
            c = open(os.path.join(workdir, f"{prod}-B-out", "world.at"), "rb").read()
            assert a == c, f"{prod}: cold A->B world.at not byte-equal"
        results[f"{prod}/cold_regen"] = "byte-equal products from closure"


def control_mutation_sensitivity(results, workdir):
    # bg11-main：speed 2.0 -> 2.5 必须改变 world sha（语义编辑到达产物；
    # 绑定值在 root 实例面，改的是参数列不是名字表）。
    pdir = os.path.join(PRODUCTS_DIR, "bg11-main")
    mdir = os.path.join(workdir, "bg11-main-mut")
    os.makedirs(mdir, exist_ok=True)
    for name in os.listdir(os.path.join(pdir, "closure")):
        text = read(os.path.join(pdir, "closure", name))
        if name == "main.at":
            assert "speed: 2.0" in text, "mutation anchor missing"
            text = text.replace("speed: 2.0", "speed: 2.5")
        shutil.copyfile(os.path.join(pdir, "closure", name), os.path.join(mdir, name))
        if name == "main.at":
            with open(os.path.join(mdir, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    r = lower(os.path.join(mdir, "main.at"), os.path.join(workdir, "bg11-main-mut-out"))
    assert r.returncode == 0, f"mutant regen failed: {r.stderr}"
    a = sha256_file(os.path.join(pdir, "world.at"))
    c = sha256_file(os.path.join(workdir, "bg11-main-mut-out", "world.at"))
    assert a != c, "semantic source change must move the world sha"
    results["bg11-main/mutation_sensitivity"] = "speed 2.0->2.5 changes the world sha"

    # 注释独占编辑必须字节不变。
    cdir = os.path.join(workdir, "bg11-main-comment")
    os.makedirs(cdir, exist_ok=True)
    for name in os.listdir(os.path.join(pdir, "closure")):
        text = read(os.path.join(pdir, "closure", name))
        if name == "main.at":
            text = "// comment-only mutation probe (plan030)\n" + text
        with open(os.path.join(cdir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    r = lower(os.path.join(cdir, "main.at"), os.path.join(workdir, "bg11-main-comment-out"))
    assert r.returncode == 0, f"comment mutant regen failed: {r.stderr}"
    a = open(os.path.join(pdir, "world.at"), "rb").read()
    c = open(os.path.join(workdir, "bg11-main-comment-out", "world.at"), "rb").read()
    assert a == c, "comment-only mutation must leave the world byte-identical"
    results["bg11-main/comment_mutation_ignored"] = "comment-only edit -> byte-equal world"


def control_negatives(results):
    for prod, needle in NEGATIVES:
        entry = os.path.join(FIXTURES, prod, "main.at")
        out = os.path.join(tempfile.gettempdir(), "plan030-neg", prod)
        r = lower(entry, out)
        assert r.returncode != 0, f"{prod}: negative fixture must be rejected"
        combined = (r.stderr or "") + (r.stdout or "")
        assert needle in combined, (
            f"{prod}: rejection '{combined.strip()}' does not name '{needle}'"
        )
        assert (
            "symbol '" in combined
            or ".at" in combined
            or "at line " in combined
            or "research parse" in combined
        ), f"{prod}: rejection lacks a location anchor"
        results[f"{prod}/negative"] = needle


def control_frozen_sources(results):
    # 受信 driver 运行时 API 字节（001/002 已交付面，本计划不改）。
    drv = os.path.join(REPO, "experimental", "autographics-auto-driver", "api")
    for name, want in DRIVER_API_PINS.items():
        got = sha256_file(os.path.join(drv, name))
        assert got == want, f"{name}: {got} != {want}"
    # Gallery 只读基线（内容迁移另有合同；本计划只读消费）。
    for path, want in GALLERY_BASELINE:
        got = sha256_file(path)
        assert got == want, f"gallery baseline drift: {path}"
    # 027/028 canonical spec 字节不变（028 档是本计划的直接冻结基底）。
    assert sha256_file(SPEC_027) == SPEC_027_SHA, "027 spec must stay frozen"
    assert sha256_file(SPEC_028) == SPEC_028_SHA, "028 spec must stay frozen"
    results["frozen_sources"] = "driver apis + gallery baseline + 027/028 specs pinned"


def control_old_profile_freeze(results, workdir):
    # 旧档输出冻结：027 g07a 与 028 g11-main 从各自闭包再生成必须与在库
    # 产品字节一致（本计划对旧档唯一共享面改动 = refs/bindings 档门后新增）。
    exe = os.path.join(PILOT, "target", "debug", "node2d-lower.exe")

    def regen(prod_dir, profile, tag, artifacts):
        b = os.path.join(workdir, f"{tag}-B")
        os.makedirs(b, exist_ok=True)
        for name in os.listdir(os.path.join(prod_dir, "closure")):
            shutil.copyfile(os.path.join(prod_dir, "closure", name), os.path.join(b, name))
        r = subprocess.run(
            [exe, "--profile", profile, "--entry", os.path.join(b, "main.at"),
             "--out", os.path.join(workdir, f"{tag}-B-out")],
            capture_output=True, text=True,
        )
        assert r.returncode == 0, f"{tag} regen failed: {r.stderr}"
        for artifact in artifacts:
            a = open(os.path.join(prod_dir, artifact), "rb").read()
            c = open(os.path.join(workdir, f"{tag}-B-out", artifact), "rb").read()
            assert a == c, f"{tag} {artifact} drifted (old profile freeze)"

    regen(
        os.path.join(PILOT, "generated-components3d-runtime", "g07a"),
        "components-3d-runtime",
        "g07a-027",
        ("scene.agscene", "world.at"),
    )
    regen(
        os.path.join(PILOT, "generated-components3d-events", "g11-main"),
        "components-3d-events",
        "g11-028",
        ("scene.agscene", "world.at"),
    )
    results["old_profile_freeze"] = "027 g07a + 028 g11-main products byte-equal from closure"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--controls", action="store_true")
    args = ap.parse_args()
    if not args.controls:
        print("usage: verify_plan030.py --controls")
        return 2
    results = {}
    workdir = tempfile.mkdtemp(prefix="plan030-verify-")
    try:
        control_identity(results)
        control_template_rows(results)
        control_cold_regen(results, workdir)
        control_mutation_sensitivity(results, workdir)
        control_negatives(results)
        control_frozen_sources(results)
        control_old_profile_freeze(results, workdir)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    width = max(len(k) for k in results)
    for k in sorted(results):
        print(f"  {k:<{width}}  {results[k]}")
    print(f"PASS plan030 controls: {len(results)} checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
