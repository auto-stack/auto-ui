"""PLAN-032 verify controls: identity binding for the frozen
generated-components2d-runtime/g2 product (world/scene sha chain, closure
manifest, runner provenance), cold regeneration byte equality from the
committed fixture, the frozen skeleton contract pins on the generated bytes
(snapshot store + snapshot poll, single-element batch despawn, generated
patrol/restart, kind=0 closeout — and NO idle-turn gate, no cursor reads, no
per-direction held reads), the named negative lowering rejection, and the
driver consumption suites (route/budget on the hand-proven AND generated
worlds, admission battery, real-Host media) invoked as subprocesses.
Raw evidence stays local; the durable record is the Plan receipt. Run from
any cwd:

  python experimental/autographics-node2d-pilot/tools/verify_plan032.py --controls
"""
import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
FIXTURE = ROOT / "fixtures" / "components2d-runtime" / "g2"
GENERATED = ROOT / "generated-components2d-runtime" / "g2"
DRIVER_DIR = REPO / "experimental" / "autographics-auto-driver"

GENERATOR_ID = "autographics-node2d-pilot plan032 components-2d-runtime"
API = "autographics.components2d/1"
WORLD_SHA = "d0c6c196ea73d45bb7d66198aa1b614b09da1145a91608ef63919ceaea44a0ac"
MODULES = {
    "main",
    "player",
    "coin",
    "enemy",
    "goal",
    "pit",
    "resources",
    "hudmap",
    "statusmap",
}
ASSETS = {
    "b0b740dc49e51abefff9bb1af830080fe00f817b468614992040d438d6171c3d.wav",
    "lilita_one_regular.ttf",
    "license.txt",
    "8fde96f66bf875ec06cfe7058348cd572c469413381e8204b1cd5973058998df.png",
}
CONSUMERS = [
    "experimental/autographics-auto-driver/tests/node2d_full_game_flow.rs",
    "experimental/autographics-auto-driver/tests/node2d_full_game_media.rs",
    "experimental/autographics-auto-driver/tests/node2d_full_game_generated.rs",
]


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def run_lower(entry: pathlib.Path, out: pathlib.Path) -> None:
    cmd = [
        "cargo",
        "run",
        "--locked",
        "--offline",
        "--bin",
        "node2d-lower",
        "--",
        "--profile",
        "components-2d-runtime",
        "--entry",
        str(entry),
        "--out",
        str(out),
    ]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=1800)
    if r.returncode != 0:
        raise AssertionError(f"lowering failed: {r.stderr.strip()[:400]}")


def run_lower_expect_error(entry: pathlib.Path, out: pathlib.Path) -> str:
    cmd = [
        "cargo",
        "run",
        "--locked",
        "--offline",
        "--bin",
        "node2d-lower",
        "--",
        "--profile",
        "components-2d-runtime",
        "--entry",
        str(entry),
        "--out",
        str(out),
    ]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=1800)
    assert r.returncode != 0, "lowering must fail"
    return r.stderr + r.stdout


def check_identity(out_dir: pathlib.Path) -> None:
    identity = json.loads((out_dir / "identity.json").read_text(encoding="utf-8"))
    assert identity["generator"] == GENERATOR_ID, identity["generator"]
    assert identity["api"] == API, identity["api"]
    doc = json.loads((out_dir / "scene.agscene").read_text(encoding="utf-8"))
    assert doc["schema"] == "autographics.scene/8"
    assert doc["behavior"]["api"] == API
    assert doc["behavior"]["actors"]["two_d"] == 1
    world = (out_dir / "world.at").read_bytes()
    source_sha = doc["behavior"]["source"]["sha256"]
    assert source_sha == sha(world), "scene binds the world source"
    assert source_sha == WORLD_SHA, "committed world sha drift"
    assert doc["behavior"]["source"]["byte_length"] == len(world)
    assert identity["user_source_sha256"] == source_sha
    names = [o["name"] for o in doc["objects"]]
    assert len(names) == len(set(names)), "duplicate scene object names"
    # the atlas sprite binding rides the character row
    char_row = next(o for o in doc["objects"] if o["name"] == "player.body")
    assert char_row["sprite"] == {
        "asset": "sha256:8fde96f66bf875ec06cfe7058348cd572c469413381e8204b1cd5973058998df",
        "frame": [0, 0, 32, 32],
        "flip": False,
    }, char_row["sprite"]
    # cues and hud slots
    assert [c["name"] for c in doc["cues"]] == ["coin", "win", "fail", "jump"]
    assert [s["slot"] for s in doc["hud"]["slots"]] == [0, 1, 2, 3]
    # closure manifest: exact module set, hashes and bytes
    modules = {
        c["name"].split("asset:")[-1].removesuffix(".wav").removesuffix(".ttf").removesuffix(".txt").removesuffix(".png"): c
        for c in identity["closure"]
        if not c["name"].startswith("asset:")
    }
    assert modules.keys() == MODULES, modules.keys()
    for mod, rec in modules.items():
        f = out_dir / "closure" / f"{mod}.at"
        assert f.is_file(), f"closure file {mod} missing"
        data = f.read_bytes()
        assert rec["sha256"] == sha(data), f"closure hash {mod}"
        assert rec["bytes"] == len(data), f"closure bytes {mod}"
        fixture = FIXTURE / f"{mod}.at"
        assert sha(fixture.read_bytes()) == rec["sha256"], f"fixture {mod} drifted"
    asset_names = {c["name"].split("asset:")[-1] for c in identity["closure"] if c["name"].startswith("asset:")}
    assert asset_names == ASSETS, asset_names
    prov = identity["provenance"]
    assert prov["product"] == "g2"
    assert prov["world_sha256"] == source_sha
    first_consumer = prov["consumer"].split(" (")[0].split(" + ")[0]
    consumer = REPO / first_consumer
    assert consumer.is_file(), f"consumer test file missing: {consumer}"
    for listed in CONSUMERS:
        rel = str(pathlib.Path(listed).as_posix())
        assert any(rel in c for c in [prov["consumer"]]) or (REPO / listed).is_file()


def check_skeleton(world: str) -> None:
    pins = [
        " r_snap = ag_actions_snapshot()",
        " cmp_events()",
        "let n = ag_events_snapshot()",
        "ag_event_snap_pair(i)",
        "ag_object_despawn_batch(1, coin_handle[j], 0, 0, 0, 0, 0, 0, 0)",
        "fn cmp_patrol(dt float)",
        "ag_object_move(enemy_handle[0]",
        "fn cmp_restart()",
        "ag_round_request()",
        "ag_present2d(0, ",
        "cmp_frame_x(player_pose[0])",
        "cmp_flip()",
        "if (r_np < 5)",
    ]
    for pin in pins:
        assert pin in world, f"skeleton pin missing: {pin}"
    bans = [
        "ag_event_next(",
        "ag_action_held(",
        "ag_action_pressed(",
        "halt",
        "ag_object_despawn(",
    ]
    for ban in bans:
        assert ban not in world, f"banned construct present: {ban}"


def check_negative() -> None:
    with tempfile.TemporaryDirectory() as td:
        out = pathlib.Path(td) / "neg"
        bad = pathlib.Path(td) / "bad.at"
        main = (FIXTURE / "main.at").read_text(encoding="utf-8")
        mutated = main.replace("var state = 0", "var status = 0").replace(
            'text_field: "state"', 'text_field: "status"'
        )
        bad.write_text(mutated, encoding="utf-8")
        text = run_lower_expect_error(bad, out)
        assert "state" in text, text[:400]


def run_driver_test(test: str, timeout: int) -> None:
    cmd = [
        "cargo",
        "test",
        "--locked",
        "--offline",
        "--manifest-path",
        str(DRIVER_DIR / "Cargo.toml"),
        "--test",
        test,
        "--",
        "--test-threads=1",
    ]
    env = dict(**{k: v for k, v in __import__("os").environ.items()})
    env["CARGO_TERM_COLOR"] = "never"
    env["RUST_MIN_STACK"] = "16777216"
    r = subprocess.run(cmd, cwd=DRIVER_DIR, capture_output=True, text=True, timeout=timeout, env=env)
    assert r.returncode == 0, f"{test} failed:\n{r.stdout[-1500:]}\n{r.stderr[-800:]}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--controls", action="store_true")
    ap.add_argument(
        "--skip-driver",
        action="store_true",
        help="skip the driver consumption suites (route/budget/admission/media)",
    )
    args = ap.parse_args()
    if not args.controls:
        print(__doc__)
        return 0

    # a. cold regeneration from the committed fixture is byte-identical
    with tempfile.TemporaryDirectory() as td:
        regen = pathlib.Path(td) / "g2"
        run_lower(FIXTURE / "main.at", regen)
        for f in ("scene.agscene", "identity.json", "world.at"):
            a = (GENERATED / f).read_bytes()
            b = (regen / f).read_bytes()
            assert a == b, f"{f} regeneration differs"
        check_identity(regen)
        world = (regen / "world.at").read_text(encoding="utf-8")
        check_skeleton(world)

    # b. named negative rejection (missing frozen root state)
    check_negative()

    # c. driver consumption suites (single instance each)
    if not args.skip_driver:
        run_driver_test("public_2d_composition_api", 600)
        run_driver_test("node2d_full_game_flow", 900)
        run_driver_test("node2d_full_game_generated", 900)
        run_driver_test("node2d_full_game_media", 1200)

    print(
        "PLAN032 verify controls: regeneration byte-identical, identity/closure/provenance bound, "
        "skeleton contract pinned, negative named; driver suites "
        + ("skipped" if args.skip_driver else "green")
        + "."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
