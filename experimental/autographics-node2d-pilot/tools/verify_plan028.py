def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def lower(entry, out):
    exe = os.path.join(PILOT, "target", "debug", "node2d-lower.exe")
    return subprocess.run(
        [exe, "--profile", "components-3d-events", "--entry", entry, "--out", out],
        capture_output=True, text=True,
    )


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def jload(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def control_identity(results):
    for prod in PRODUCTS:
        pdir = os.path.join(PRODUCTS_DIR, prod)
        identity = jload(os.path.join(pdir, "identity.json"))
        assert identity["generator"] == GENERATOR, f"{prod}: generator string"
        assert identity["api"] == API, f"{prod}: assembly identity"
        world = os.path.join(pdir, "world.at")
        assert identity["user_source_sha256"] == sha256_file(world), (
            f"{prod}: user_source sha mismatch"
        )
        # closure 模块哈希 == fixture 源字节。
        for entry in identity["closure"]:
            name = entry["name"]
            src = os.path.join(FIXTURES, prod, f"{name}.at")
            assert entry["sha256"] == sha256_file(src), f"{prod}: closure {name} drift"
        scene = jload(os.path.join(pdir, "scene.agscene"))
        assert scene["behavior"]["api"] == API, f"{prod}: scene behavior api"
        # document_id = doc_prefix + root 模块名（各产品同为 main 入口）。
        assert scene["document_id"] == "plan028-components-3d-events-main", (
            f"{prod}: document id {scene['document_id']}"
        )
        results[f"{prod}/identity"] = "generator/api/sha/closure pinned"


def control_template_rows(results):
    scene = jload(os.path.join(PRODUCTS_DIR, "g11-main", "scene.agscene"))
    objs = scene["objects"]
    assert len(objs) == 8, f"g11-main scene rows {len(objs)}"
    want = [
        ("ground", "cylinder"),
        ("Main/hero/body", "cylinder"),
        ("ShardA", "mob"),
        ("ShardB", "mob"),
        ("ShardC", "mob"),
        ("Saw", "cylinder"),
        ("Beacon", "cylinder"),
        ("VoidZone", "cylinder"),
    ]
    got = [(o["name"], o["kind"]) for o in objs]
    assert got == want, f"g11-main rows {got}"
    scales = [o["scale"] for o in objs[2:5]]
    assert scales == [[0.5, 0.5, 0.5], [0.6, 0.6, 0.6], [0.7, 0.7, 0.7]], scales
    assert all(not o["visible"] for o in objs[2:]), "templates park invisible"
    # 角色编辑位姿 y=1（Start place 后 tick0 y=0.5 的区别保留在行里）。
    assert objs[1]["translation"] == [3.0, 1.0, -3.0], objs[1]["translation"]
    results["g11-main/template_rows"] = "8 rows; shard scales 0.5/0.6/0.7; park invisible"


def control_cold_regen(results, workdir):
    for prod in PRODUCTS:
        pdir = os.path.join(PRODUCTS_DIR, prod)
        identity = jload(os.path.join(pdir, "identity.json"))
        b = os.path.join(workdir, f"{prod}-B")
        os.makedirs(b, exist_ok=True)
        for name in os.listdir(os.path.join(pdir, "closure")):
            shutil.copyfile(os.path.join(pdir, "closure", name), os.path.join(b, name))
        r = lower(os.path.join(b, "main.at"), os.path.join(workdir, f"{prod}-B-out"))
        assert r.returncode == 0, f"{prod}: cold regen failed: {r.stderr}"
        for artifact in ("scene.agscene",):
            a = open(os.path.join(pdir, artifact), "rb").read()
            c = open(os.path.join(workdir, f"{prod}-B-out", artifact), "rb").read()
            assert a == c, f"{prod}: cold A->B {artifact} not byte-equal"
        if identity["user_source_sha256"] is not None:
            a = open(os.path.join(pdir, "world.at"), "rb").read()
            c = open(os.path.join(workdir, f"{prod}-B-out", "world.at"), "rb").read()
            assert a == c, f"{prod}: cold A->B world.at not byte-equal"
        results[f"{prod}/cold_regen"] = "byte-equal products from closure"


def control_mutation_sensitivity(results, workdir):
    # g11-main：speed 2.0 -> 2.5 必须改变 world sha（语义编辑到达产物）。
    pdir = os.path.join(PRODUCTS_DIR, "g11-main")
    mdir = os.path.join(workdir, "g11-main-mut")
    os.makedirs(mdir, exist_ok=True)
    for name in os.listdir(os.path.join(pdir, "closure")):
        text = read(os.path.join(pdir, "closure", name))
        if name == "character.at":
            assert "var speed = 2.0" in text, "mutation anchor missing"
            text = text.replace("var speed = 2.0", "var speed = 2.5")
        shutil.copyfile(os.path.join(pdir, "closure", name), os.path.join(mdir, name))
        if name == "character.at":
            with open(os.path.join(mdir, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    r = lower(os.path.join(mdir, "main.at"), os.path.join(workdir, "g11-main-mut-out"))
    assert r.returncode == 0, f"mutant regen failed: {r.stderr}"
    a = sha256_file(os.path.join(pdir, "world.at"))
    c = sha256_file(os.path.join(workdir, "g11-main-mut-out", "world.at"))
    assert a != c, "semantic source change must move the world sha"
    results["g11-main/mutation_sensitivity"] = "speed 2.0->2.5 changes the world sha"

    # 注释独占编辑必须字节不变。
    cdir = os.path.join(workdir, "g11-main-comment")
    os.makedirs(cdir, exist_ok=True)
    for name in os.listdir(os.path.join(pdir, "closure")):
        text = read(os.path.join(pdir, "closure", name))
        if name == "character.at":
            text = "// comment-only mutation probe (plan028)\n" + text
        with open(os.path.join(cdir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    r = lower(os.path.join(cdir, "main.at"), os.path.join(workdir, "g11-main-comment-out"))
    assert r.returncode == 0, f"comment mutant regen failed: {r.stderr}"
    a = open(os.path.join(pdir, "world.at"), "rb").read()
    c = open(os.path.join(workdir, "g11-main-comment-out", "world.at"), "rb").read()
    assert a == c, "comment-only mutation must leave the world byte-identical"
    results["g11-main/comment_mutation_ignored"] = "comment-only edit -> byte-equal world"


def control_negatives(results):
    for prod, needle in NEGATIVES:
        entry = os.path.join(FIXTURES, prod, "main.at")
        out = os.path.join(tempfile.gettempdir(), "plan028-neg", prod)
        r = lower(entry, out)
        assert r.returncode != 0, f"{prod}: negative fixture must be rejected"
        combined = (r.stderr or "") + (r.stdout or "")
        assert needle in combined, (
            f"{prod}: rejection '{combined.strip()}' does not name '{needle}'"
        )
        assert "symbol '" in combined or ".at" in combined or "at line " in combined, (
            f"{prod}: rejection lacks a location anchor"
        )
        results[f"{prod}/negative"] = needle


def control_frozen_sources(results):
    # 受信 driver 运行时 API 字节（001/002 已交付面，本计划不改）。
    drv = os.path.join(REPO, "experimental", "autographics-auto-driver", "api")
    for name, want in DRIVER_API_PINS.items():
        got = sha256_file(os.path.join(drv, name))
        assert got == want, f"{name}: {got} != {want}"
    # Gallery 只读基线（内容迁移另有合同；本计划只读消费）。
    for path, want in GALLERY_BASELINE:
        got = sha256_file(path)
        assert got == want, f"gallery baseline drift: {path}"
    # 027 canonical spec 字节不变。
    assert sha256_file(SPEC_027) == SPEC_027_SHA, "027 spec must stay frozen"
    results["frozen_sources"] = "driver apis + gallery baseline + 027 spec pinned"


