def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--controls", action="store_true")
    args = ap.parse_args()
    if not args.controls:
        print("usage: verify_plan028.py --controls")
        return 2
    results = {}
    workdir = tempfile.mkdtemp(prefix="plan028-verify-")
    try:
        control_identity(results)
        control_template_rows(results)
        control_cold_regen(results, workdir)
        control_mutation_sensitivity(results, workdir)
        control_negatives(results)
        control_frozen_sources(results)
        control_old_profile_freeze(results, workdir)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    width = max(len(k) for k in results)
    for k in sorted(results):
        print(f"  {k:<{width}}  {results[k]}")
    print(f"PASS plan028 controls: {len(results)} checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
