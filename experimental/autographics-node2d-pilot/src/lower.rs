//! 实例表 → 单文件 AG 用户源 + 场景文档（合同 §2 段 5）。
//!
//! 降层形状（合同 S3/S5 冻结）：每 node 定义一组 SoA 数组；处理器是
//! 真实 Auto 函数（实例索引参数）；事件经绑定表投递到正确父实例；
//! 条件分支的真假变化由差量执行器 spawn/despawn（非 hidden）；
//! 玩法规则（巡逻、收集守卫、销毁）全部在生成的 Auto 里。

use crate::load::{node_of, Project};
use crate::translate::{translate_stmts, Ctx, LowerError, Target};
use auto_parser_api::ast::{Expr, Stmt};
use auto_ui_dialect::node2d::{EventPattern, NodeDecl, PropValue, View2dElement};
use std::collections::BTreeMap;

pub struct LowerOutput {
    /// 生成的单文件用户源（AG `Api::Triggers2V1` 准入面）。
    pub user_source: String,
    /// 触发 pair → 实例 gid（测试/验证用映射）。
    pub pair_to_instance: Vec<usize>,
    /// 场景文档 JSON 文本（autographics.scene/8）。
    pub scene_json: String,
    /// 行为源身份。
    pub source_sha256: String,
    pub source_bytes: usize,
}

pub fn lower_project(project: &Project) -> Result<LowerOutput, LowerError> {
    let root_name = project.root.clone();
    let root = node_of(project, &root_name);

    // ---- 实例表（含嵌套实例树：非 root 定义的 view 也产生实例）----
    let root_view = root
        .view2d
        .as_ref()
        .ok_or_else(|| LowerError::Unsupported {
            what: "root node has no view-2d".into(),
            line: 0,
        })?;
    let mut instances: Vec<Instance> = Vec::new();
    let mut per_def: BTreeMap<String, usize> = Default::default();
    let mut gid = 1usize;
    for el in &root_view.elements {
        collect_instances(el, None, None, &mut instances, &mut gid, &mut per_def);
    }
    // 广度优先展开子实例：每个非 root 定义的 view 对其每个实例各展开
    // 一遍（同定义实例的子树互不共享状态）。
    loop {
        let mut expanded = false;
        let defs_with_children: Vec<String> = {
            let mut ds: Vec<String> = Vec::new();
            for inst in &instances {
                if inst.owner.is_none() {
                    let node = node_of(project, &inst.node);
                    if let Some(view) = &node.view2d {
                        if view.elements.iter().any(|e| {
                            matches!(e, View2dElement::Instance { .. } | View2dElement::If { .. })
                        }) && !ds.contains(&inst.node)
                        {
                            ds.push(inst.node.clone());
                        }
                    }
                }
            }
            ds
        };
        for def in &defs_with_children {
            let owners: Vec<Instance> = instances
                .iter()
                .filter(|i| &i.node == def)
                .cloned()
                .collect();
            for owner in &owners {
                // 防重复展开：该 owner 的子实例已存在则跳过。
                if instances.iter().any(|i| i.owner == Some(owner.gid)) {
                    continue;
                }
                let node = node_of(project, def);
                if let Some(view) = &node.view2d {
                    let before = instances.len();
                    for el in &view.elements {
                        collect_instances(
                            el,
                            None,
                            Some(owner.gid),
                            &mut instances,
                            &mut gid,
                            &mut per_def,
                        );
                    }
                    if instances.len() > before {
                        expanded = true;
                    }
                }
            }
        }
        if !expanded {
            break;
        }
    }

    // ---- 前缀/定义表 ----
    let mut prefixes: BTreeMap<String, String> = Default::default();
    prefixes.insert(root_name.clone(), "r".to_string());
    let defs = defs_sorted(&instances);
    for def in &defs {
        prefixes.insert(def.clone(), def.to_lowercase());
    }

    // ---- 运行时初始化标记：属性为父成员引用的字段在 app_start 赋值 ----
    for inst in instances.iter_mut() {
        let node = node_of(project, &inst.node);
        let mut runtime_fields = Vec::new();
        for (pname, _pty) in &node.params {
            if pname == "on_collect" || pname == "target" {
                continue;
            }
            if let Some(pr) = inst.props.iter().find(|pr| &pr.name == pname) {
                if !matches!(
                    pr.value,
                    PropValue::One(Expr::Float(..)) | PropValue::One(Expr::Int(..))
                ) {
                    runtime_fields.push(pname.clone());
                }
            }
        }
        inst.runtime_init = runtime_fields;
    }

    // ---- 触发标记与 slot/pair 分配（发射顺序）----
    mark_triggers(project, &mut instances);
    let mut next_slot = 0usize;
    for inst in instances.iter_mut() {
        if inst.trigger {
            inst.slot = Some(next_slot);
            next_slot += 1;
        }
    }
    let pair_to_instance: Vec<usize> = instances
        .iter()
        .filter(|i| i.trigger)
        .map(|i| i.gid)
        .collect();

    let mut src = String::new();
    src.push_str("// GENERATED by autographics-node2d-pilot (PLAN-016 contract S3/S5).\n");
    src.push_str(&format!(
        "// Root: {root_name}; instances: {}\n",
        instances
            .iter()
            .map(|i| format!("{}:{}", i.name, i.node))
            .collect::<Vec<_>>()
            .join(",")
    ));
    src.push_str("// Regeneration must be byte-identical (tools/verify_plan016.py).\n");
    src.push_str("var ok=0.0\n");

    // ---- 枚举常量 ----
    for module in project.modules.values() {
        for (ename, variants) in &module.enums {
            for (vname, value) in variants {
                src.push_str(&format!(
                    "var {}_{}={value}\n",
                    ename.to_uppercase(),
                    vname.to_uppercase()
                ));
            }
        }
    }

    // ---- 状态存储 ----
    emit_state(project, root, &instances, &prefixes, &mut src)?;

    // ---- 池化纯函数（verbatim 源切片：文本定位 + 花括号配平）----
    for module in project.modules.values() {
        for (fname, _span) in &module.fns {
            let text =
                slice_fn_source(&module.source, fname).ok_or_else(|| LowerError::Unsupported {
                    what: format!("fn {fname} source slice"),
                    line: 0,
                })?;
            src.push_str(&format!("// pooled fn {fname} from {}\n", module.name));
            src.push_str(text.trim_end());
            src.push('\n');
        }
    }

    // ---- 处理器 ----
    emit_handlers(project, root, &instances, &prefixes, &mut src)?;

    // ---- 读回 getter（纯 Auto，零计费）----
    emit_getters(project, root, &instances, &prefixes, &mut src)?;

    // ---- 编排 ----
    let camera = root_view.elements.iter().find_map(|el| match el {
        View2dElement::Camera { props, .. } => Some(props.clone()),
        _ => None,
    });
    emit_orchestration(
        project,
        root,
        &instances,
        &prefixes,
        &pair_to_instance,
        camera.as_ref(),
        &mut src,
    )?;

    let source_bytes = src.len();
    let source_sha256 = crate::scene::sha256_hex(src.as_bytes());
    let scene_json =
        crate::scene::build_scene_json(project, &instances, &source_sha256, source_bytes);

    Ok(LowerOutput {
        user_source: src,
        pair_to_instance,
        scene_json,
        source_sha256,
        source_bytes,
    })
}

#[derive(Debug, Clone)]
pub struct Instance {
    pub gid: usize,
    pub node: String,
    pub name: String,
    pub idx: usize,
    pub props: Vec<auto_ui_dialect::node2d::Prop>,
    pub conditional: Option<Expr>,
    /// 定义 view-2d 里有 trigger2d（AG 触发实例）。
    pub trigger: bool,
    /// slot/pair（触发实例按发射顺序分配）。
    pub slot: Option<usize>,
    /// 所属父实例 gid（嵌套实例树；根直属为 None）。
    pub owner: Option<usize>,
    /// 实例属性为父成员引用、需在 app_start 运行时初始化的字段。
    pub runtime_init: Vec<String>,
}

#[allow(clippy::too_many_arguments)]
fn collect_instances(
    el: &View2dElement,
    cond: Option<Expr>,
    owner: Option<usize>,
    out: &mut Vec<Instance>,
    gid: &mut usize,
    per_def: &mut BTreeMap<String, usize>,
) {
    match el {
        View2dElement::Instance { node, name, props } => {
            let idx = per_def.get(node).copied().unwrap_or(0);
            per_def.insert(node.clone(), idx + 1);
            out.push(Instance {
                gid: *gid,
                node: node.clone(),
                name: name.clone(),
                idx,
                props: props.clone(),
                conditional: cond,
                trigger: false,
                slot: None,
                owner,
                runtime_init: Vec::new(),
            });
            *gid += 1;
        }
        View2dElement::If { cond, then } => {
            for child in then {
                collect_instances(child, Some(cond.clone()), owner, out, gid, per_def);
            }
        }
        _ => {}
    }
}

fn defs_sorted(instances: &[Instance]) -> Vec<String> {
    let mut defs: Vec<String> = Vec::new();
    for i in instances {
        if !defs.contains(&i.node) {
            defs.push(i.node.clone());
        }
    }
    defs.sort();
    defs
}

fn numeric_lit(e: &Expr) -> Option<f64> {
    match e {
        Expr::Float(v, _) => Some(*v),
        Expr::Int(v) => Some(*v as f64),
        Expr::Unary(op, inner) if matches!(op, auto_parser_api::ast::Op::Sub) => {
            numeric_lit(inner).map(|v| -v)
        }
        _ => None,
    }
}

fn fmt_f(v: f64) -> String {
    if v == v.trunc() && v.abs() < 1e15 {
        format!("{v:.1}")
    } else {
        format!("{v}")
    }
}

/// node 定义的状态字段：数值参数（序）+ model 字段，带 int 判定。
fn def_fields(node: &NodeDecl) -> Vec<(String, bool)> {
    let mut fields = Vec::new();
    for (pname, _ty) in &node.params {
        if pname == "on_collect" || pname == "target" {
            continue;
        }
        fields.push((pname.clone(), false));
    }
    if let Some(model) = &node.model {
        for f in &model.fields {
            let is_int = matches!((&f.ty, &f.init), (auto_parser_api::ast::Type::Int, _))
                || matches!(f.init, Expr::Int(_));
            fields.push((f.name.to_string(), is_int));
        }
    }
    fields
}

fn emit_state(
    project: &Project,
    root: &NodeDecl,
    instances: &[Instance],
    prefixes: &BTreeMap<String, String>,
    src: &mut String,
) -> Result<(), LowerError> {
    let rprefix = &prefixes[&root.name];
    if let Some(model) = &root.model {
        for f in &model.fields {
            let lit = match &f.init {
                Expr::Int(v) => format!("{v}"),
                Expr::Float(_, raw) => raw.to_string(),
                other => {
                    return Err(LowerError::Unsupported {
                        what: format!("root model init {other:?}"),
                        line: 0,
                    })
                }
            };
            src.push_str(&format!("var {rprefix}_{}={lit}\n", f.name));
        }
    }
    for def in defs_sorted(instances) {
        let node = node_of(project, &def);
        let prefix = &prefixes[&def];
        let own: Vec<&Instance> = instances
            .iter()
            .filter(|i| i.node.as_str() == def)
            .collect();
        for (field, _) in &def_fields(node) {
            let mut values = Vec::new();
            for inst in &own {
                let v = if let Some(pv) = inst
                    .props
                    .iter()
                    .find(|p| &p.name == field)
                    .map(|p| &p.value)
                {
                    match pv {
                        PropValue::One(e) => numeric_lit(e).unwrap_or(0.0), // 父成员引用字段：0 占位，app_start 运行时初始化
                        PropValue::Pair(_) => {
                            return Err(LowerError::Unsupported {
                                what: format!("instance {} prop {field} pair", inst.name),
                                line: 0,
                            })
                        }
                    }
                } else {
                    let model = node.model.as_ref().ok_or_else(|| LowerError::Unsupported {
                        what: format!("field {field} missing on {def}"),
                        line: 0,
                    })?;
                    let mf = model
                        .fields
                        .iter()
                        .find(|f| &f.name.to_string() == field)
                        .ok_or_else(|| LowerError::Unsupported {
                            what: format!("field {field} missing on {def}"),
                            line: 0,
                        })?;
                    match &mf.init {
                        Expr::Int(v) => *v as f64,
                        Expr::Float(v, _) => *v,
                        Expr::Ident(p) => {
                            let pv = inst
                                .props
                                .iter()
                                .find(|pr| &pr.name == p)
                                .map(|pr| &pr.value)
                                .ok_or_else(|| LowerError::Unsupported {
                                    what: format!("model init references unknown param {p}"),
                                    line: 0,
                                })?;
                            match pv {
                                PropValue::One(e) => {
                                    numeric_lit(e).ok_or_else(|| LowerError::Unsupported {
                                        what: format!("param {p} not numeric"),
                                        line: 0,
                                    })?
                                }
                                _ => {
                                    return Err(LowerError::Unsupported {
                                        what: format!("param {p} pair"),
                                        line: 0,
                                    })
                                }
                            }
                        }
                        other => {
                            return Err(LowerError::Unsupported {
                                what: format!("model init {other:?}"),
                                line: 0,
                            })
                        }
                    }
                };
                values.push(v);
            }
            let is_int = def_fields(node)
                .into_iter()
                .find(|(n, _)| n == field)
                .map(|(_, ii)| ii)
                .unwrap_or(false);
            let list = values
                .iter()
                .map(|v| {
                    if is_int {
                        format!("{}", *v as i64)
                    } else {
                        fmt_f(*v)
                    }
                })
                .collect::<Vec<_>>()
                .join(",");
            src.push_str(&format!("var {prefix}_{field}=[{list}]\n"));
        }
        let needs_handle = own.iter().any(|i| i.trigger);
        let needs_alive = own.iter().any(|i| i.conditional.is_some());
        if needs_handle {
            let zeros = own.iter().map(|_| "0").collect::<Vec<_>>().join(",");
            src.push_str(&format!("var {prefix}_handle=[{zeros}]\n"));
        }
        if needs_alive {
            let ones = own.iter().map(|_| "1").collect::<Vec<_>>().join(",");
            src.push_str(&format!("var {prefix}_alive=[{ones}]\n"));
            src.push_str(&format!("var {prefix}_spawned=[{ones}]\n"));
        }
        if node.params.iter().any(|(n, _)| n == "target") {
            let zeros = own.iter().map(|_| "0").collect::<Vec<_>>().join(",");
            src.push_str(&format!("var {prefix}_target=[{zeros}]\n"));
        }
    }
    // 事件绑定表（非 root 父实例投递：每实例目标，按同定义实例序）。
    for def in defs_sorted(instances) {
        let inst = match instances.iter().find(|i| i.node.as_str() == def) {
            Some(i) => i,
            None => continue,
        };
        let Some(pr) = inst.props.iter().find(|pr| pr.name == "on_collect") else {
            continue;
        };
        let any_non_root = instances
            .iter()
            .filter(|i| i.node.as_str() == def)
            .any(|i| i.owner.is_some());
        if !any_non_root {
            continue;
        }
        let event = match &pr.value {
            PropValue::One(Expr::Call(c)) => match &*c.name {
                Expr::Dot(inner, ev) => {
                    if matches!(&**inner, Expr::Ident(_)) {
                        ev.clone()
                    } else {
                        continue;
                    }
                }
                _ => continue,
            },
            // 裸 `.Ev` 绑定（无载荷）。
            PropValue::One(Expr::Dot(inner, ev)) => {
                if matches!(&**inner, Expr::Ident(_)) {
                    ev.clone()
                } else {
                    continue;
                }
            }
            _ => continue,
        };
        let prefix = &prefixes[def.as_str()];
        let targets: Vec<String> = instances
            .iter()
            .filter(|i| i.node.as_str() == def)
            .map(|i| {
                let owner = i
                    .owner
                    .and_then(|gid| instances.iter().find(|o| o.gid == gid))
                    .expect("owner");
                owner.idx.to_string()
            })
            .collect();
        src.push_str(&format!(
            "var {prefix}_bind_{}=[{}]\n",
            snake(&event).to_uppercase(),
            targets.join(",")
        ));
    }
    Ok(())
}

fn base_ctx<'a>(
    project: &'a Project,
    node_name: &str,
    prefixes: &'a BTreeMap<String, String>,
) -> Ctx<'a> {
    let is_root = node_name == project.root;
    Ctx {
        target: if is_root {
            Target::Root
        } else {
            Target::Instance {
                prefix: prefixes[node_name].clone(),
                index: "i".to_string(),
            }
        },
        emit_hook: Box::new(|event: &str| {
            Err(LowerError::Unsupported {
                what: format!("emit .{event} without binding"),
                line: 0,
            })
        }),
        enum_path: Box::new(|ename: &str, variant: &str| {
            for module in project.modules.values() {
                if let Some(variants) = module.enums.get(ename) {
                    if variants.contains_key(variant) {
                        return Some(format!(
                            "{}_{}",
                            ename.to_uppercase(),
                            variant.to_uppercase()
                        ));
                    }
                }
            }
            None
        }),
    }
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// 同定义实例的 on_collect 绑定（fixture 每定义一种绑定）。
fn instance_emit_hook<'a>(
    project: &'a Project,
    def: &str,
    instances: &'a [Instance],
    prefixes: &'a BTreeMap<String, String>,
) -> Result<Box<dyn Fn(&str) -> Result<String, LowerError> + 'a>, LowerError> {
    let inst =
        instances
            .iter()
            .find(|i| &i.node == def)
            .ok_or_else(|| LowerError::Unsupported {
                what: format!("handler for def {def} without instance"),
                line: 0,
            })?;
    let binding = inst
        .props
        .iter()
        .find(|pr| pr.name == "on_collect")
        .map(|pr| pr.value.clone());
    let ctx = base_ctx(project, def, prefixes);
    // 绑定形态：`.Ev`（无载荷）或 `.Ev(arg...)`（Call）。
    let (target, binding_args): (String, Vec<Expr>) = match &binding {
        None => (String::new(), Vec::new()),
        Some(PropValue::One(Expr::Call(c))) => {
            let t = match &*c.name {
                Expr::Dot(inner, ev) => {
                    if matches!(&**inner, Expr::Ident(_)) {
                        ev.clone()
                    } else {
                        return Err(LowerError::Unsupported {
                            what: format!("on_collect binding {c:?}"),
                            line: 0,
                        });
                    }
                }
                other => {
                    return Err(LowerError::Unsupported {
                        what: format!("on_collect binding {other:?}"),
                        line: 0,
                    })
                }
            };
            let mut args = Vec::new();
            for a in &c.args.args {
                match a {
                    auto_parser_api::ast::Arg::Pos(e) => args.push(e.clone()),
                    other => {
                        return Err(LowerError::Unsupported {
                            what: format!("binding arg {other:?}"),
                            line: 0,
                        })
                    }
                }
            }
            (t.to_string(), args)
        }
        Some(PropValue::One(Expr::Dot(inner, ev))) => {
            if matches!(&**inner, Expr::Ident(_)) {
                (ev.to_string(), Vec::new())
            } else {
                return Err(LowerError::Unsupported {
                    what: format!("on_collect binding {binding:?}"),
                    line: 0,
                });
            }
        }
        Some(other) => {
            return Err(LowerError::Unsupported {
                what: format!("on_collect binding value {other:?}"),
                line: 0,
            })
        }
    };
    let mut args = Vec::new();
    for e in &binding_args {
        let mut buf = String::new();
        translate_stmts(&[Stmt::Expr(e.clone())], &ctx, &mut buf, 0)?;
        args.push(buf.trim().to_string());
    }
    let call: Option<String> = if target.is_empty() {
        None
    } else {
        let base = snake(&project.root);
        Some(format!("{base}_{}({})", snake(&target), args.join(", ")))
    };
    // 非 root 父实例投递：绑定表按实例路由（collector_grab(coin_bind_GRAB[i])）。
    let routed_call: Option<String> = {
        let own: Vec<&Instance> = instances.iter().filter(|i| &i.node == def).collect();
        let non_root: Vec<usize> = own.iter().filter_map(|i| i.owner).collect();
        if non_root.is_empty() {
            None
        } else {
            let inst = instances.iter().find(|i| &i.node == def).unwrap();
            // 绑定形态：`.Ev`（无载荷）或 `.Ev(arg...)`。
            let (target, _call_args): (String, Vec<Expr>) = match inst
                .props
                .iter()
                .find(|pr| pr.name == "on_collect")
                .map(|pr| &pr.value)
            {
                Some(PropValue::One(Expr::Call(c))) => {
                    let t = match &*c.name {
                        Expr::Dot(inner, ev) => {
                            if matches!(&**inner, Expr::Ident(_)) {
                                ev.to_string()
                            } else {
                                return Err(LowerError::Unsupported {
                                    what: format!("routed binding {c:?}"),
                                    line: 0,
                                });
                            }
                        }
                        other => {
                            return Err(LowerError::Unsupported {
                                what: format!("routed binding {other:?}"),
                                line: 0,
                            })
                        }
                    };
                    (t, Vec::new())
                }
                Some(PropValue::One(Expr::Dot(inner, ev))) => {
                    if matches!(&**inner, Expr::Ident(_)) {
                        (ev.to_string(), Vec::new())
                    } else {
                        return Err(LowerError::Unsupported {
                            what: "routed binding bare dot must be self member".into(),
                            line: 0,
                        });
                    }
                }
                other => {
                    return Err(LowerError::Unsupported {
                        what: format!("routed binding {other:?}"),
                        line: 0,
                    })
                }
            };
            // 所有非 root owner 必须同定义（fixture 约束）。
            let mut owner_defs: Vec<String> = Vec::new();
            for gid in &non_root {
                let o = instances.iter().find(|i| i.gid == *gid).ok_or_else(|| {
                    LowerError::Unsupported {
                        what: "owner missing".into(),
                        line: 0,
                    }
                })?;
                if !owner_defs.contains(&o.node) {
                    owner_defs.push(o.node.clone());
                }
            }
            if owner_defs.len() != 1 {
                return Err(LowerError::Unsupported {
                    what: format!("mixed owner defs {owner_defs:?}"),
                    line: 0,
                });
            }
            let parent_base = snake(&owner_defs[0]);
            let prefix = &prefixes[def];
            let table = format!("{prefix}_bind_{}", snake(&target).to_uppercase());
            let arg_text = String::new();
            Some(format!(
                "{parent_base}_{}({table}[i]{arg_text})",
                snake(&target)
            ))
        }
    };
    let final_call = routed_call.or(call);
    Ok(Box::new(move |event: &str| match &final_call {
        Some(c) => Ok(c.clone()),
        None => Err(LowerError::Unsupported {
            what: format!("emit .{event} without on_collect binding"),
            line: 0,
        }),
    }))
}

fn emit_handlers(
    project: &Project,
    root: &NodeDecl,
    instances: &[Instance],
    prefixes: &BTreeMap<String, String>,
    src: &mut String,
) -> Result<(), LowerError> {
    // 根处理器（016 根不 emit）。
    if let Some(on) = &root.on {
        let base = snake(&root.name);
        for h in &on.handlers {
            let (suffix, params): (String, String) = match &h.pattern {
                EventPattern::Life { event, .. } => {
                    let e = event.to_lowercase();
                    let ps = if e == "tick" {
                        "dt float".into()
                    } else {
                        String::new()
                    };
                    (format!("life{e}"), ps)
                }
                EventPattern::Member { name, params } => {
                    let ps = params
                        .iter()
                        .map(|p| format!("{p} int"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    (snake(name), ps)
                }
            };
            src.push_str(&format!("fn {base}_{suffix}({params}) {{\n"));
            let ctx = base_ctx(project, &root.name, prefixes);
            translate_stmts(&h.body.stmts, &ctx, src, 1)?;
            src.push_str("}\n");
        }
    }
    // 非 root 定义处理器（首参实例索引 i）。
    for def in defs_sorted(instances) {
        let node = node_of(project, &def);
        let Some(on) = &node.on else { continue };
        let base = snake(&def);
        let hook = instance_emit_hook(project, &def, instances, prefixes)?;
        for h in &on.handlers {
            let suffix = match &h.pattern {
                EventPattern::Life { event, .. } => format!("life{}", event.to_lowercase()),
                EventPattern::Member { name, .. } => snake(name),
            };
            let extra = match &h.pattern {
                EventPattern::Life { event, .. } => {
                    if event.to_lowercase() == "tick" {
                        ", dt float".to_string()
                    } else {
                        String::new()
                    }
                }
                EventPattern::Member { params, .. } => params
                    .iter()
                    .map(|p| format!(", {p} int"))
                    .collect::<Vec<_>>()
                    .join(""),
            };
            src.push_str(&format!("fn {base}_{suffix}(i int{extra}) {{\n"));
            let mut ctx = base_ctx(project, &def, prefixes);
            ctx.emit_hook = Box::new(&*hook);
            translate_stmts(&h.body.stmts, &ctx, src, 1)?;
            src.push_str("}\n");
        }
    }
    Ok(())
}

fn emit_getters(
    project: &Project,
    root: &NodeDecl,
    instances: &[Instance],
    prefixes: &BTreeMap<String, String>,
    src: &mut String,
) -> Result<(), LowerError> {
    let _ = project;
    let rprefix = &prefixes[&root.name];
    if let Some(model) = &root.model {
        for f in &model.fields {
            let name = f.name.to_string();
            let is_int = matches!(f.init, Expr::Int(_));
            let ty = if is_int { "int" } else { "float" };
            src.push_str(&format!(
                "fn get_{rprefix}_{name}() {ty} {{return {rprefix}_{name}}}\n"
            ));
        }
    }
    for def in defs_sorted(instances) {
        let node = node_of(project, &def);
        let prefix = &prefixes[&def];
        let own: Vec<&Instance> = instances
            .iter()
            .filter(|i| i.node.as_str() == def)
            .collect();
        // 同定义实例重名（如各自 view 内都叫 c）时用 def+idx 前缀，
        // 避免 duplicate root symbol。
        let mut names: Vec<String> = own.iter().map(|i| i.name.clone()).collect();
        names.sort();
        names.dedup();
        let collision = names.len() != own.len()
            || own.iter().any(|i| {
                instances
                    .iter()
                    .any(|o| o.node.as_str() != def && o.name == i.name)
            });
        let getter = |inst: &Instance| -> String {
            if collision {
                format!("{}{}", def.to_lowercase(), inst.idx)
            } else {
                inst.name.clone()
            }
        };
        for (field, is_int) in &def_fields(node) {
            let ty = if *is_int { "int" } else { "float" };
            for inst in &own {
                src.push_str(&format!(
                    "fn get_{}_{field}() {ty} {{return {prefix}_{field}[{}]}}\n",
                    getter(inst),
                    inst.idx
                ));
            }
        }
        if own.iter().any(|i| i.trigger) {
            for inst in &own {
                src.push_str(&format!(
                    "fn get_{}_handle() int {{return {prefix}_handle[{}]}}\n",
                    getter(inst),
                    inst.idx
                ));
            }
        }
        if own.iter().any(|i| i.conditional.is_some()) {
            for inst in &own {
                src.push_str(&format!(
                    "fn get_{}_alive() int {{return {prefix}_alive[{}]}}\n",
                    getter(inst),
                    inst.idx
                ));
            }
        }
        // char 绑定定义（冻结场景表：player 模板 = 文档行 0）的世界位置
        // 读回（ag_local 纯读，零计费）。
        if def == "Player" {
            src.push_str(
                "fn get_player_node_x() float {return ag_local(0,0)}\nfn get_player_node_y() float {return ag_local(0,1)}\n",
            );
        }
    }
    Ok(())
}

fn prop_pair(inst: &Instance, key: &str) -> Option<(f64, f64)> {
    let v = inst
        .props
        .iter()
        .find(|pr| pr.name == key)
        .map(|pr| &pr.value)?;
    let es = match v {
        PropValue::Pair(es) => es.clone(),
        PropValue::One(Expr::Tuple(es)) => es.clone(),
        _ => return None,
    };
    if es.len() != 2 {
        return None;
    }
    Some((numeric_lit(&es[0])?, numeric_lit(&es[1])?))
}

fn lit_f(e: &Expr) -> Result<f64, LowerError> {
    numeric_lit(e).ok_or_else(|| LowerError::Unsupported {
        what: format!("literal {e:?}"),
        line: 0,
    })
}

#[allow(clippy::too_many_arguments)]
fn emit_orchestration(
    project: &Project,
    root: &NodeDecl,
    instances: &[Instance],
    prefixes: &BTreeMap<String, String>,
    pair_to_instance: &[usize],
    camera: Option<&Vec<auto_ui_dialect::node2d::Prop>>,
    src: &mut String,
) -> Result<(), LowerError> {
    let rbase = snake(&root.name);

    // ---- app_start ----
    src.push_str("fn app_start() {\n");
    src.push_str(&format!(" {rbase}_lifestart()\n"));
    for inst in instances {
        if def_has_life(project, &inst.node, "Start") {
            let base = snake(&inst.node);
            src.push_str(&format!(" {base}_lifestart({})\n", inst.idx));
        }
    }
    for inst in instances {
        let node = node_of(project, &inst.node);
        if node.params.iter().any(|(n, _)| n == "target") {
            let prefix = &prefixes[&inst.node];
            src.push_str(&format!(" {prefix}_target[{}]=ag_actor(2)\n", inst.idx));
        }
    }
    // 父成员引用字段的运行时初始化（以所属父实例上下文翻译属性表达式）。
    for inst in instances {
        if inst.runtime_init.is_empty() {
            continue;
        }
        let owner = inst
            .owner
            .and_then(|gid| instances.iter().find(|i| i.gid == gid))
            .ok_or_else(|| LowerError::Unsupported {
                what: format!("runtime-init field on root-d instance {}", inst.name),
                line: 0,
            })?;
        let prefix = &prefixes[&inst.node];
        for fname in &inst.runtime_init {
            let pr = inst
                .props
                .iter()
                .find(|pr| &pr.name == fname)
                .ok_or_else(|| LowerError::Unsupported {
                    what: format!("runtime field {fname} missing"),
                    line: 0,
                })?;
            let mut ctx = base_ctx(project, &owner.node, prefixes);
            ctx.target = Target::Instance {
                prefix: prefixes[&owner.node].clone(),
                index: owner.idx.to_string(),
            };
            let mut buf = String::new();
            let ev = match &pr.value {
                PropValue::One(e) => e.clone(),
                PropValue::Pair(_) => {
                    return Err(LowerError::Unsupported {
                        what: "runtime-init pair".into(),
                        line: 0,
                    })
                }
            };
            translate_stmts(&[Stmt::Expr(ev)], &ctx, &mut buf, 0)?;
            let text = buf.trim().to_string();
            src.push_str(&format!(" {prefix}_{fname}[{}]={text}\n", inst.idx));
        }
    }
    for (pair, gid) in pair_to_instance.iter().enumerate() {
        let inst = instances.iter().find(|i| i.gid == *gid).unwrap();
        let prefix = &prefixes[&inst.node];
        let template = crate::scene::template_id(inst);
        let pos = trigger_spawn_pos(project, inst, prefixes)?;
        src.push_str(&format!(
            " {prefix}_handle[{0}]=ag_object_spawn({pair}, {template}, {1}, {2}, 0.0)\n",
            inst.idx, pos.0, pos.1
        ));
        src.push_str(&format!(
            " ok=ok+ag_trigger_bind({pair}, 1, 1, {prefix}_handle[{0}], 0, 0.0)*1.0\n",
            inst.idx
        ));
    }
    src.push_str(" ok=ok+ag_char_bind(1)*1.0\n");
    if let Some(props) = camera {
        let mut vals = Vec::new();
        for key in ["min", "max", "view_size"] {
            let v = props
                .iter()
                .find(|pr| &pr.name == key)
                .map(|pr| pr.value.clone())
                .ok_or_else(|| LowerError::Unsupported {
                    what: format!("camera missing {key}"),
                    line: 0,
                })?;
            let es = match v {
                PropValue::Pair(es) => es,
                PropValue::One(Expr::Tuple(es)) => es,
                other => {
                    return Err(LowerError::Unsupported {
                        what: format!("camera {key} {other:?}"),
                        line: 0,
                    })
                }
            };
            if es.len() != 2 {
                return Err(LowerError::Unsupported {
                    what: format!("camera {key} arity"),
                    line: 0,
                });
            }
            vals.push((lit_f(&es[0])?, lit_f(&es[1])?));
        }
        src.push_str(&format!(
            " ok=ok+ag_camera_follow_2d(1, {}, {}, {}, {}, {}, {})*1.0\n",
            fmt_f(vals[0].0),
            fmt_f(vals[0].1),
            fmt_f(vals[1].0),
            fmt_f(vals[1].1),
            fmt_f(vals[2].0),
            fmt_f(vals[2].1)
        ));
    }
    src.push_str("}\n");

    // ---- app_update（合同 S3 固定顺序）----
    src.push_str("fn app_update(dt float) {\n");
    src.push_str(&format!(" {rbase}_lifetick(dt)\n"));
    for inst in instances {
        if def_has_life(project, &inst.node, "Tick") {
            let base = snake(&inst.node);
            src.push_str(&format!(" {base}_lifetick({}, dt)\n", inst.idx));
        }
    }
    src.push_str(" var n=ag_event_next()\n");
    src.push_str(" if n==1 {\n");
    src.push_str("  let p=ag_event_pair()\n");
    for (pair_idx, gid) in pair_to_instance.iter().enumerate() {
        let inst = instances.iter().find(|i| i.gid == *gid).unwrap();
        let node = node_of(project, &inst.node);
        let handler_opt = node.on.as_ref().and_then(|on| {
            on.handlers.iter().find_map(|h| match &h.pattern {
                EventPattern::Member { name, params } => Some((name.clone(), params.len())),
                _ => None,
            })
        });
        // 无业务处理器的触发实例（016 Hazard：仅运动状态）：事件由游标
        // 推进消费，不投递。
        if let Some(handler) = handler_opt {
            let base = snake(&inst.node);
            let actor_arg = if handler.1 >= 1 { "ag_actor(2)" } else { "" };
            let comma = if handler.1 >= 1 { ", " } else { "" };
            src.push_str(&format!(
                "  if p=={pair_idx} {{ {base}_{}({}{}{}) }}\n",
                snake(&handler.0),
                inst.idx,
                comma,
                actor_arg
            ));
        }
    }
    src.push_str(" }\n");
    // 条件差量执行器（真 spawn/despawn，非 hidden）。
    for inst in instances {
        let Some(cond) = &inst.conditional else {
            continue;
        };
        let prefix = &prefixes[&inst.node];
        let has_trigger = inst.trigger;
        let mut cond_text = String::new();
        let ctx = base_ctx(project, &root.name, prefixes);
        translate_stmts(&[Stmt::Expr(cond.clone())], &ctx, &mut cond_text, 0)?;
        let cond_text = cond_text
            .trim()
            .trim_start_matches('(')
            .trim_end_matches(')')
            .to_string();
        let template = crate::scene::template_id(inst);
        let pos = trigger_spawn_pos(project, inst, prefixes)?;
        let pair = pair_to_instance
            .iter()
            .position(|g| *g == inst.gid)
            .unwrap_or(255);
        src.push_str(&format!(" if {cond_text} {{\n"));
        src.push_str(&format!("  if {prefix}_spawned[{}]==0 {{\n", inst.idx));
        src.push_str(&format!("   {prefix}_spawned[{}]=1\n", inst.idx));
        src.push_str(&format!("   {prefix}_alive[{}]=1\n", inst.idx));
        src.push_str(&format!(
            "   {prefix}_handle[{0}]=ag_object_spawn({pair}, {template}, {1}, {2}, 0.0)\n",
            inst.idx, pos.0, pos.1
        ));
        if has_trigger {
            src.push_str(&format!(
                "   ok=ok+ag_trigger_bind({pair}, 1, 1, {prefix}_handle[{0}], 0, 0.0)*1.0\n",
                inst.idx
            ));
        }
        src.push_str("  }\n");
        src.push_str(" } else {\n");
        src.push_str(&format!("  if {prefix}_spawned[{}]==1 {{\n", inst.idx));
        src.push_str(&format!("   {prefix}_spawned[{}]=0\n", inst.idx));
        src.push_str(&format!("   {prefix}_alive[{}]=0\n", inst.idx));
        src.push_str(&format!(
            "   ok=ok+ag_object_despawn({prefix}_handle[{0}])*1.0\n",
            inst.idx
        ));
        src.push_str("  }\n");
        src.push_str(" }\n");
    }
    src.push_str("}\n");
    Ok(())
}

fn def_has_life(project: &Project, node_name: &str, event: &str) -> bool {
    let node = node_of(project, node_name);
    node.on.as_ref().is_some_and(|on| {
        on.handlers
            .iter()
            .any(|h| matches!(&h.pattern, EventPattern::Life { event: e, .. } if e == event))
    })
}

/// 实例的触发标记 + slot 分配（在 lower 入口完成一次）。
pub fn mark_triggers(project: &Project, instances: &mut [Instance]) {
    for inst in instances.iter_mut() {
        let node = node_of(project, &inst.node);
        inst.trigger = node.view2d.as_ref().is_some_and(|v| {
            v.elements
                .iter()
                .any(|e| matches!(e, View2dElement::Trigger { .. }))
        });
    }
}

/// 在模块源里按文本定位 `fn name(` 并按花括号配平切出完整定义。
fn slice_fn_source(source: &str, name: &str) -> Option<String> {
    let marker = format!("fn {name}(");
    let start = source.find(&marker)?;
    let open = source[start..].find('{')? + start;
    let mut depth = 0usize;
    for (i, c) in source[open..].char_indices() {
        match c {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(source[start..open + i + 1].to_string());
                }
            }
            _ => {}
        }
    }
    None
}

/// 实例触发体 position 的生成文本：(x_text, y_text)。
fn trigger_spawn_pos(
    project: &Project,
    inst: &Instance,
    prefixes: &BTreeMap<String, String>,
) -> Result<(String, String), LowerError> {
    let node = node_of(project, &inst.node);
    let view = node
        .view2d
        .as_ref()
        .ok_or_else(|| LowerError::Unsupported {
            what: format!("node {} has no view-2d", inst.node),
            line: 0,
        })?;
    let pos = view
        .elements
        .iter()
        .find_map(|e| match e {
            View2dElement::Trigger { props, .. } => props
                .iter()
                .find(|pr| pr.name == "position")
                .map(|pr| pr.value.clone()),
            _ => None,
        })
        .ok_or_else(|| LowerError::Unsupported {
            what: format!("node {} trigger missing position", inst.node),
            line: 0,
        })?;
    let es = match pos {
        PropValue::Pair(es) => es,
        PropValue::One(Expr::Tuple(es)) => es,
        other => {
            return Err(LowerError::Unsupported {
                what: format!("trigger position {other:?}"),
                line: 0,
            })
        }
    };
    if es.len() != 2 {
        return Err(LowerError::Unsupported {
            what: "trigger position arity".into(),
            line: 0,
        });
    }
    let mut ctx = base_ctx(project, &inst.node, prefixes);
    ctx.target = Target::Instance {
        prefix: prefixes[&inst.node].clone(),
        index: inst.idx.to_string(),
    };
    let mut tx = String::new();
    translate_stmts(&[Stmt::Expr(es[0].clone())], &ctx, &mut tx, 0)?;
    let mut ty = String::new();
    translate_stmts(&[Stmt::Expr(es[1].clone())], &ctx, &mut ty, 0)?;
    Ok((tx.trim().to_string(), ty.trim().to_string()))
}
