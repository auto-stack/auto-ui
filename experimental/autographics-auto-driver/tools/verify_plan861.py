"""Verify the committed PLAN-861 source closure, including text transport rules."""
import hashlib, json, pathlib, subprocess, sys

root = pathlib.Path(__file__).resolve().parents[1]
base = root.parent
try:
    identity = json.loads((root / "research/plan861-identity.json").read_text())
except Exception as e:
    raise AssertionError(f"source set drift: identity unreadable: {e}")
assert not (base / ".cargo").exists(), "source set drift: shared experimental .cargo configuration"
for package, allowed_dirs in {
    "autographics-auto-driver": {"api", "research", "samples", "src", "tests", "tools", "target", ".sdk-source"},
    "autographics-prototype": {"assets", "research", "src", "testdata", "tests", "target"},
}.items():
    directory = base / package
    expected = {p for p in identity["files"] if pathlib.PurePosixPath(p).parent.as_posix() == package}
    assert not any(p.is_symlink() or p.is_junction() for p in directory.iterdir()), f"linked source: package root {package}"
    actual = {p.relative_to(base).as_posix() for p in directory.iterdir() if p.is_file()}
    assert actual == expected, f"source set drift: package root {package}: {actual ^ expected}"
    unexpected = {p.name for p in directory.iterdir() if p.is_dir()} - allowed_dirs
    assert not unexpected, f"source set drift: package directories {package}: {unexpected}"
for relative, expected in identity["files"].items():
    raw = base / relative
    assert not any(v.is_symlink() or v.is_junction() for v in [raw, *raw.parents] if v != base.parent), f"linked source: {relative}"
    p = raw.resolve()
    assert base.resolve() in p.parents and p.is_file(), f"missing/outside source: {relative}"
    b = p.read_bytes()
    if p.suffix.lower() in identity["text_suffixes"] or p.name.lower() in identity["text_suffixes"]:
        b = b.replace(b"\r\n", b"\n")
    assert hashlib.sha256(b).hexdigest() == expected, f"source hash mismatch: {relative}"
for folder in identity["folders"]:
    # Volatile run reports (regenerated by every probe run) are not part of
    # the frozen source closure.
    actual = {p.relative_to(base).as_posix() for p in (base / folder).rglob("*") if p.is_file() and "__pycache__" not in p.parts and "target" not in p.parts and p.name != "window-report.json"}
    expected = {p for p in identity["files"] if p.startswith(folder + "/") and not p.endswith("window-report.json")}
    assert actual == expected, f"source set drift: {folder}: {actual ^ expected}"
assert identity["base_commit"] == "7b4e89e6b54701c29aaa9138bcf55d176d58051e", "PLAN-861 base is the 860 landing commit"
sdk_pin = json.loads((root / "research/baseline.json.txt").read_text())["sdk"]["repository_commit"]
assert identity["sdk_commit"] == sdk_pin, "SDK artifact pin mismatch"
for required in [
    "autographics-auto-driver/api/character2d_v1.at",
    "autographics-auto-driver/src/authoring/game_input.rs",
    "autographics-auto-driver/tests/character2d_api.rs",
    "autographics-auto-driver/tests/game_input.rs",
    "autographics-auto-driver/tests/character2d_host.rs",
    "autographics-auto-driver/tests/character2d_samples.rs",
    "autographics-auto-driver/tools/check_character2d.py",
    "autographics-auto-driver/samples/character2d/layout_a.agscene",
    "autographics-auto-driver/samples/character2d/layout_b.agscene",
    "autographics-auto-driver/samples/character2d/main.at",
    "autographics-auto-driver/samples/character2d/main-fast.at",
]:
    assert required in identity["files"], f"861 source unlisted: {required}"
print(f"PASS PLAN-861 source/asset identity: {len(identity['files'])} hashes; profile/tools/samples bound")

if "--controls" in sys.argv:
    paths = [
        root / "api/character2d_v1.at",
        root / "src/authoring/game_input.rs",
        root / "samples/character2d/main.at",
        root / "research/plan861-identity.json",
    ]
    original = [p.read_bytes() for p in paths]
    added = root / "src/authoring/unlisted_control.rs"
    assert not added.exists()

    def rejected():
        result = subprocess.run([sys.executable, __file__], capture_output=True)
        assert result.returncode != 0 and any(
            v in result.stderr
            for v in [b"source hash mismatch", b"missing/outside source", b"source set drift", b"SDK artifact pin mismatch", b"861 source unlisted"]
        ), result.stderr

    try:
        for i, p in enumerate(paths):
            saved = p.read_bytes()
            p.unlink()
            rejected()
            p.write_bytes(saved)
        added.write_text("// unlisted source")
        rejected()
        added.unlink()
        d = json.loads(original[3])
        d["files"]["autographics-auto-driver/api/character2d_v1.at"] = "0" * 64
        (root / "research/plan861-identity.json").write_bytes(json.dumps(d).encode())
        rejected()
    finally:
        for i, p in enumerate(paths):
            p.write_bytes(original[i])
        if added.exists():
            added.unlink()
    print("PASS probe source deletion, unlisted source, wrong identity hash and restored control")
